// @ts-check
/**
 * APG Disclosure Pattern
 * https://www.w3.org/WAI/ARIA/apg/patterns/disclosure/
 *
 * Derived from apg-usecases `patterns/disclosure/*.uc.yaml`:
 *   disclosure-accessibility-features, disclosure-keyboard-toggle,
 *   disclosure-visual-indicators
 *
 * The demo renders one collapsed disclosure: a native `<button>` carrying
 * aria-expanded and aria-controls, plus a content `<div>` that is shown and
 * hidden with a `hidden` class (`display: none`). The button also contains a
 * "▼"/"▲" indicator marked aria-hidden.
 *
 * Collapsed-on-load is the state worth starting from: it is the only one from
 * which both halves of the interaction — expand and collapse — can be driven
 * in a single pass.
 */
const { test, expect } = require('@playwright/test');
const { gotoPattern, tabUntilFocused, isFocused } = require('./support/apg');

const TITLE = 'Click Me';
const BODY = 'This is the content to be displayed when the disclosure is open.';

/**
 * Resolve the content element through the button's own aria-controls, rather
 * than by class. The id is generated by React's useId and contains colons, so
 * it needs an attribute selector rather than a `#id` one.
 */
async function controlledContent(page, control) {
  await expect(control, 'the disclosure control must reference its content').toHaveAttribute(
    'aria-controls',
    /\S/
  );
  const id = await control.getAttribute('aria-controls');
  return page.locator(`[id="${id}"]`);
}

test.beforeEach(async ({ page }) => {
  await gotoPattern(page, 'disclosure');
});

test.describe('Disclosure — roles, states, and properties', () => {
  test('the control is a button whose aria-controls resolves to the hidden content', async ({
    page,
  }) => {
    const control = page.getByRole('button', { name: TITLE });
    const content = await controlledContent(page, control);

    await expect(control).toHaveAttribute('aria-expanded', 'false');
    // aria-controls must point at a real element and that element must
    // genuinely not be perceivable while collapsed.
    await expect(content).toHaveCount(1);
    await expect(content).toBeHidden();

    await control.click();

    await expect(control).toHaveAttribute('aria-expanded', 'true');
    await expect(content).toBeVisible();
    await expect(content).toHaveText(BODY);
  });

  test('the state indicator is decorative and never enters the accessible name', async ({
    page,
  }) => {
    // disclosure-visual-indicators: the chevron is a sighted-user affordance.
    // It has to change with the state *and* stay out of the accessibility
    // tree, otherwise the control renames itself every time it is used.
    const control = page.getByRole('button', { name: TITLE });
    const indicator = control.locator('.indicator');

    await expect(indicator).toHaveAttribute('aria-hidden', 'true');
    await expect(indicator).toHaveText('▼');
    await expect(control).toHaveAccessibleName(TITLE);

    await tabUntilFocused(page, control);
    await page.keyboard.press('Enter');

    await expect(control).toHaveAttribute('aria-expanded', 'true');
    await expect(indicator).toHaveText('▲');
    await expect(control).toHaveAccessibleName(TITLE);
  });
});

test.describe('Disclosure — keyboard operation', () => {
  test('Enter expands the disclosure and reveals its content', async ({ page }) => {
    const control = page.getByRole('button', { name: TITLE });
    const content = await controlledContent(page, control);

    await expect(content).toBeHidden();

    const presses = await tabUntilFocused(page, control);
    expect(presses, 'the disclosure control must be reachable by Tab').toBeGreaterThan(0);
    await page.keyboard.press('Enter');

    await expect(control).toHaveAttribute('aria-expanded', 'true');
    await expect(content).toBeVisible();
  });

  test('Space collapses an expanded disclosure', async ({ page }) => {
    const control = page.getByRole('button', { name: TITLE });
    const content = await controlledContent(page, control);

    await tabUntilFocused(page, control);
    await page.keyboard.press('Enter');
    await expect(content).toBeVisible();

    await page.keyboard.press('Space');

    await expect(control).toHaveAttribute('aria-expanded', 'false');
    await expect(content).toBeHidden();
  });

  test('Space alone toggles the disclosure in both directions', async ({ page }) => {
    // A single keypress must produce a single toggle. A handler that both
    // calls its own toggle and lets the native button click through would flip
    // twice and appear to do nothing at all.
    const control = page.getByRole('button', { name: TITLE });
    const content = await controlledContent(page, control);

    await tabUntilFocused(page, control);

    await page.keyboard.press('Space');
    await expect(control).toHaveAttribute('aria-expanded', 'true');
    await expect(content).toBeVisible();

    await page.keyboard.press('Space');
    await expect(control).toHaveAttribute('aria-expanded', 'false');
    await expect(content).toBeHidden();
  });

  test('expanding leaves focus on the control', async ({ page }) => {
    // A disclosure reveals content in place; it opens no new context, so focus
    // must not be moved into the revealed region.
    const control = page.getByRole('button', { name: TITLE });

    await tabUntilFocused(page, control);
    await page.keyboard.press('Enter');

    await expect(control).toHaveAttribute('aria-expanded', 'true');
    expect(await isFocused(control), 'focus must stay on the disclosure control').toBe(true);
  });

  test('the revealed content adds no tab stops of its own', async ({ page }) => {
    const control = page.getByRole('button', { name: TITLE });
    const content = await controlledContent(page, control);

    await tabUntilFocused(page, control);
    await page.keyboard.press('Enter');
    await expect(content).toBeVisible();

    await page.keyboard.press('Tab');

    const landedInContent = await content.evaluate((el) => el.contains(document.activeElement));
    expect(landedInContent, 'static disclosure content must not be focusable').toBe(false);
    expect(await isFocused(control), 'Tab must move off the control').toBe(false);
  });
});

test.describe('Disclosure — pointer operation', () => {
  test('clicking the control toggles the content in both directions', async ({ page }) => {
    const control = page.getByRole('button', { name: TITLE });
    const content = await controlledContent(page, control);

    await control.click();
    await expect(control).toHaveAttribute('aria-expanded', 'true');
    await expect(content).toBeVisible();

    await control.click();
    await expect(control).toHaveAttribute('aria-expanded', 'false');
    await expect(content).toBeHidden();
  });
});
